// Generates a 64x64 blue-noise rank tile with the void-and-cluster method (Ulichney 1993)
// and writes it to src/core/bluenoise.js. Deterministic (fixed seed).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const N = 64;
const SIZE = N * N;
const SIGMA = 1.5;

function mulberry32(seed) {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Toroidal Gaussian kernel indexed by (dy*N + dx).
const kernel = new Float64Array(SIZE);
for (let dy = 0; dy < N; dy++) {
  for (let dx = 0; dx < N; dx++) {
    const ddx = Math.min(dx, N - dx);
    const ddy = Math.min(dy, N - dy);
    kernel[dy * N + dx] = Math.exp(-(ddx * ddx + ddy * ddy) / (2 * SIGMA * SIGMA));
  }
}

function addEnergy(energy, idx, sign) {
  const x0 = idx % N;
  const y0 = (idx / N) | 0;
  for (let y = 0; y < N; y++) {
    const dy = (y - y0 + N) % N;
    for (let x = 0; x < N; x++) {
      const dx = (x - x0 + N) % N;
      energy[y * N + x] += sign * kernel[dy * N + dx];
    }
  }
}

function energyOf(bits) {
  const e = new Float64Array(SIZE);
  for (let i = 0; i < SIZE; i++) if (bits[i]) addEnergy(e, i, 1);
  return e;
}

function argBest(energy, bits, want, pickMax) {
  let best = -1;
  let bestV = pickMax ? -Infinity : Infinity;
  for (let i = 0; i < SIZE; i++) {
    if (bits[i] !== want) continue;
    const v = energy[i];
    if (pickMax ? v > bestV : v < bestV) {
      bestV = v;
      best = i;
    }
  }
  return best;
}

const rand = mulberry32(20261121);
const initial = new Uint8Array(SIZE);
const ones = Math.round(SIZE * 0.1);
let placed = 0;
while (placed < ones) {
  const i = Math.floor(rand() * SIZE);
  if (!initial[i]) {
    initial[i] = 1;
    placed++;
  }
}

// Phase 0: relax the initial pattern into a blue-noise prototype.
{
  const e = energyOf(initial);
  for (let iter = 0; iter < 10000; iter++) {
    const cluster = argBest(e, initial, 1, true);
    initial[cluster] = 0;
    addEnergy(e, cluster, -1);
    const voidIdx = argBest(e, initial, 0, false);
    if (voidIdx === cluster) {
      initial[cluster] = 1;
      addEnergy(e, cluster, 1);
      break;
    }
    initial[voidIdx] = 1;
    addEnergy(e, voidIdx, 1);
  }
}

const rank = new Int32Array(SIZE).fill(-1);

// Phase 1: remove tightest clusters from the prototype -> ranks ones-1 .. 0.
{
  const bits = initial.slice();
  const e = energyOf(bits);
  for (let r = ones - 1; r >= 0; r--) {
    const cluster = argBest(e, bits, 1, true);
    bits[cluster] = 0;
    addEnergy(e, cluster, -1);
    rank[cluster] = r;
  }
}

// Phase 2: fill largest voids up to half -> ranks ones .. SIZE/2-1.
const bits = initial.slice();
let e = energyOf(bits);
for (let r = ones; r < SIZE / 2; r++) {
  const voidIdx = argBest(e, bits, 0, false);
  bits[voidIdx] = 1;
  addEnergy(e, voidIdx, 1);
  rank[voidIdx] = r;
}

// Phase 3: with energy of the zeros (now the minority), turn the tightest zero-cluster on.
{
  const zeros = new Uint8Array(SIZE);
  for (let i = 0; i < SIZE; i++) zeros[i] = bits[i] ? 0 : 1;
  e = energyOf(zeros);
  for (let r = SIZE / 2; r < SIZE; r++) {
    const idx = argBest(e, zeros, 1, true);
    zeros[idx] = 0;
    addEnergy(e, idx, -1);
    rank[idx] = r;
  }
}

for (let i = 0; i < SIZE; i++) if (rank[i] < 0) throw new Error('unranked pixel ' + i);

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'core', 'bluenoise.js');
const lines = [];
for (let y = 0; y < N; y++) lines.push(Array.from(rank.slice(y * N, y * N + N)).join(','));
writeFileSync(
  out,
  `'use strict';
// Generated by tools/gen-bluenoise.mjs (void-and-cluster, 64x64, sigma ${SIGMA}). Do not edit.
// RANKS[y*64+x] in 0..4095; threshold n = (rank + 0.5) / 4096.
const RANKS = [
${lines.join(',\n')}
];
const NOISE = new Float32Array(4096);
for (let i = 0; i < 4096; i++) NOISE[i] = (RANKS[i] + 0.5) / 4096;
module.exports = { NOISE, SIZE: 64 };
`
);
console.log('wrote', out);
