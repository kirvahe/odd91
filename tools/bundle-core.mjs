// Bundles src/core/*.js (CommonJS) into one UMD file: build/halation-core.js.
// Defines the global HalationCore in browsers / UXP and module.exports in CommonJS hosts.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = join(root, 'src', 'core');
const files = readdirSync(coreDir).filter((f) => f.endsWith('.js')).sort();

let modules = '';
for (const f of files) {
  const name = './' + basename(f, '.js');
  const src = readFileSync(join(coreDir, f), 'utf8');
  modules += `${JSON.stringify(name)}: function (module, exports, require) {\n${src}\n},\n`;
}

const out = `/* Halation core bundle — generated by tools/bundle-core.mjs. Do not edit. */
(function (root) {
  'use strict';
  var defs = {
${modules}  };
  var cache = {};
  function req(name) {
    var key = name.replace(/\\.js$/, '');
    if (cache[key]) return cache[key].exports;
    var def = defs[key];
    if (!def) throw new Error('halation-core: module not found ' + name);
    var module = { exports: {} };
    cache[key] = module;
    def(module, module.exports, req);
    return module.exports;
  }
  var api = req('./index');
  if (typeof module === 'object' && module && module.exports) module.exports = api;
  root.HalationCore = api;
})(typeof globalThis !== 'undefined' ? globalThis : typeof window !== 'undefined' ? window : this);
`;

mkdirSync(join(root, 'build'), { recursive: true });
const target = join(root, 'build', 'halation-core.js');
writeFileSync(target, out);
console.log('wrote', target, `(${files.length} modules, ${out.length} bytes)`);
